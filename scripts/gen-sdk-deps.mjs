#!/usr/bin/env node
/**
 * Generate create-plugin's scaffold dependency list from the closure
 * single source (`scripts/lib/sdk-closure.mjs`), so the scaffolder never
 * drifts from the packed release set.
 *
 *   node scripts/gen-sdk-deps.mjs          # write src/sdk-deps.gen.ts
 *   node scripts/gen-sdk-deps.mjs --check  # exit 1 on drift (CI)
 */
import { readFileSync, writeFileSync } from "node:fs"
import { resolve } from "node:path"
import { RELEASE_SET } from "./lib/sdk-closure.mjs"
import { WORKSPACE_ROOT } from "./lib/workspace.mjs"

const OUT = resolve(
	WORKSPACE_ROOT,
	"plugins",
	"create-plugin",
	"src",
	"sdk-deps.gen.ts",
)

const names = [...RELEASE_SET].sort()
const content = `// GENERATED by scripts/gen-sdk-deps.mjs — never hand-edit.
// The published SDK closure a scaffolded plugin can depend on; kept in
// lockstep with scripts/lib/sdk-closure.mjs (see sdks:pack).
export const SDK_DEP_NAMES: readonly string[] = [
${names.map((n) => `\t"${n}",`).join("\n")}
]
`

const isCheck = process.argv.includes("--check")
if (isCheck) {
	const current = readFileSync(OUT, "utf8")
	if (current !== content) {
		console.error(
			"[gen-sdk-deps] create-plugin SDK_DEP_NAMES drifted — run `node scripts/gen-sdk-deps.mjs` and commit the change.",
		)
		process.exit(1)
	}
	console.log("[gen-sdk-deps] sdk-deps.gen.ts in sync")
} else {
	writeFileSync(OUT, content)
	console.log("[gen-sdk-deps] sdk-deps.gen.ts written")
}
